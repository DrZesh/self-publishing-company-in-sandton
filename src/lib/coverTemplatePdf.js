import { jsPDF } from 'jspdf';

// Generates a print-ready cover template PDF at the exact full-cover dimensions.
export function generateCoverPdf(dims, meta) {
  if (!dims || isNaN(dims.fullWidth) || isNaN(dims.fullHeight)) return;

  const { fullWidth, fullHeight, trimW, trimH, spine, bleed, margin, wrap, flap = 0, hinge = 0 } = dims;
  const doc = new jsPDF({ unit: 'mm', format: [fullWidth, fullHeight], orientation: 'landscape' });

  // White background
  doc.setFillColor(255, 255, 255);
  doc.rect(0, 0, fullWidth, fullHeight, 'F');

  // Layout: bleed | flap | wrap | back | hinge | spine | hinge | front | wrap | flap | bleed
  const backX = bleed + flap + wrap;
  const spineX = backX + trimW + hinge;
  const frontX = spineX + spine + hinge;
  const trimY = bleed + wrap;

  // Bleed border (red dashed)
  doc.setDrawColor(220, 38, 38);
  doc.setLineWidth(0.3);
  doc.setLineDashPattern([2, 2], 0);
  doc.rect(0.3, 0.3, fullWidth - 0.6, fullHeight - 0.6);

  // Trim lines (solid black)
  doc.setDrawColor(0, 0, 0);
  doc.setLineWidth(0.4);
  doc.setLineDashPattern([], 0);
  doc.rect(backX, trimY, trimW, trimH);
  doc.rect(frontX, trimY, trimW, trimH);
  doc.line(spineX, trimY, spineX, trimY + trimH);
  doc.line(frontX, trimY, frontX, trimY + trimH);

  // Dust jacket flaps + fold lines (blue dashed)
  if (flap > 0) {
    doc.rect(backX - flap, trimY, flap, trimH);
    doc.rect(frontX + trimW, trimY, flap, trimH);
    doc.setDrawColor(37, 99, 235);
    doc.setLineWidth(0.3);
    doc.setLineDashPattern([3, 2], 0);
    doc.line(backX, trimY, backX, trimY + trimH);
    doc.line(frontX + trimW, trimY, frontX + trimW, trimY + trimH);
    doc.setLineDashPattern([], 0);
    doc.setDrawColor(0, 0, 0);
    doc.setLineWidth(0.4);
  }

  // Safe margins (green dashed)
  doc.setDrawColor(22, 128, 60);
  doc.setLineDashPattern([3, 3], 0);
  if (trimW - margin * 2 > 0 && trimH - margin * 2 > 0) {
    doc.rect(backX + margin, trimY + margin, trimW - margin * 2, trimH - margin * 2);
    doc.rect(frontX + margin, trimY + margin, trimW - margin * 2, trimH - margin * 2);
  }
  doc.setLineDashPattern([], 0);

  // Labels
  doc.setFont(undefined, 'bold');
  doc.setFontSize(9);
  doc.setTextColor(0, 0, 0);
  doc.text('BACK COVER', backX + trimW / 2, trimY + trimH / 2, { align: 'center' });
  doc.text('FRONT COVER', frontX + trimW / 2, trimY + trimH / 2, { align: 'center' });
  if (spine > 8) {
    doc.text('SPINE', spineX + spine / 2, trimY + trimH / 2, { align: 'center', angle: 90 });
  }
  if (flap > 0) {
    doc.setFontSize(7);
    doc.text('BACK FLAP', backX - flap / 2, trimY + trimH / 2, { align: 'center', angle: 90 });
    doc.text('FRONT FLAP', frontX + trimW + flap / 2, trimY + trimH / 2, { align: 'center', angle: 90 });
    doc.setFontSize(9);
  }

  // Header info
  doc.setFont(undefined, 'bold');
  doc.setFontSize(11);
  doc.text('Book Cover Template — Creative Books SA', bleed + wrap, 8);
  doc.setFont(undefined, 'normal');
  doc.setFontSize(7);
  const info = [
    `Trim: ${meta.trimLabel}`,
    `Pages: ${meta.pages}`,
    `Paper: ${dims.paperLabel}`,
    `Binding: ${dims.bindingLabel}`,
    `Spine: ${spine.toFixed(2)} mm`,
    ...(flap > 0 ? [`Flap: ${flap.toFixed(2)} mm`, `Turn-in: ${wrap.toFixed(2)} mm`, `Hinge: ${hinge.toFixed(2)} mm`] : []),
    `Full cover: ${fullWidth.toFixed(2)} × ${fullHeight.toFixed(2)} mm`,
    `Bleed: ${bleed} mm`,
  ].join('   |   ');
  doc.text(info, bleed + wrap, 12);

  doc.setFontSize(6);
  doc.setTextColor(120, 120, 120);
  doc.text('Generated by Creative Books SA — creativebooks.co.za — Request a cover design at /getquote', fullWidth / 2, fullHeight - 3, { align: 'center' });

  doc.save(`cover-template-${meta.trimValue}-${meta.pages}p.pdf`);
}